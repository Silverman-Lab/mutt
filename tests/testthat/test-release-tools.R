test_that('permanent release tools build only from canonical staging', {
  f <- fixture_release('tiny');on.exit(unlink(f$root,recursive=TRUE))
  project <- normalizePath(test_path('..','..'))
  e <- new.env(parent=globalenv())
  withr::with_dir(project,sys.source('scripts/release.R',envir=e))
  staged_root <- file.path(f$root,'staging');dir.create(staged_root)
  file.rename(file.path(f$root,'tiny'),file.path(staged_root,'tiny'))
  out <- file.path(f$root,'built')
  candidate <- e$build_release(staged_root,'data-v1.0.0',out)
  expect_identical(candidate$studies[[1]]$status,'staged')
  expect_silent(e$validate_asset(file.path(out,'tiny.zip'),file.path(staged_root,'tiny'),candidate$studies[[1]]))
  expect_error(e$build_release(staged_root,'data-v1.0.0',out),'empty')
  expect_error(e$package_study(file.path(staged_root,'tiny'),file.path(f$root,'wrong'),'data-v2.0.0'),'version')
  writeLines('corrupt',file.path(staged_root,'tiny','aligned.rds'))
  expect_error(e$validate_study(file.path(staged_root,'tiny')),'checksum')
})
